function sectionOf(major2) {
  const n = Number(major2)
  const found = SECTION_RANGES.find(([, lo, hi]) => n >= lo && n <= hi)
  return found ? found[0] : null
}

// DART induty_code(통계청 표준산업분류, 5자리 숫자 문자열로 가정)를 받아
// 별표1 기준 { thresholdWon, label } 을 반환. 매칭 실패 시 null.
export function lookupIndustryThreshold(indutyCode) {
  const code = String(indutyCode || '').trim()
  if (!/^\d{2,}/.test(code)) return null
  const major2 = code.slice(0, 2)
  const section = sectionOf(major2)
  if (!section) return null

  if (section === 'C') {
    const key = `C${major2}`
    const hit = MANUFACTURING_THRESHOLDS[key]
    return hit ? { thresholdWon: hit[0], label: `${hit[1]} (${key})` } : null
  }
  if (section === 'E') {
    const hit = major2 === '36' ? SECTION_EXCEPTIONS.E36 : SECTION_EXCEPTIONS.E_REST
    return { thresholdWon: hit[0], label: hit[1] }
  }
  if (section === 'N') {
    const hit = major2 === '76' ? SECTION_EXCEPTIONS.N76 : SECTION_EXCEPTIONS.N_REST
    return { thresholdWon: hit[0], label: hit[1] }
  }
  if (section === 'S') {
    if (major2 === '94') return null // 협회 및 단체 — 별표1 적용 대상 아님
    const hit = SECTION_EXCEPTIONS.S_REST
    return { thresholdWon: hit[0], label: hit[1] }
  }
  if (section === 'I') {
    const hit = SECTION_EXCEPTIONS.I
    return { thresholdWon: hit[0], label: hit[1] }
  }
  const hit = SECTION_THRESHOLDS[section]
  return hit ? { thresholdWon: hit[0], label: hit[1] } : null
}
